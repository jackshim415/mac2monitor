pub fn draw_char(
    fb: &mut Framebuffer,
    x: usize,
    y: usize,
    c: char,
    color: Color,
    scale: usize,
) {
    let index = match c {
        'A'..='Z' => c as usize - 'A' as usize,
        '0'..='9' => 26 + (c as usize - '0' as usize),
        _ => return,
    };

    let glyph = FONT[index];

    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..5 {
            if bits & (1 << (4 - col)) != 0 {
                fb.fill_rect(
                    x + col * scale,
                    y + row * scale,
                    scale,
                    scale,
                    color,
                );
            }
        }
    }
}

pub fn draw_text(
    fb: &mut Framebuffer,
    x: usize,
    y: usize,
    text: &str,
    color: Color,
    scale: usize,
) {
    let char_width = 5 * scale;
    let spacing = scale;

    for (i, c) in text.chars().enumerate() {
        draw_char(
            fb,
            x + i * (char_width + spacing),
            y,
            c,
            color,
            scale,
        );
    }
}